constexpr int kMaxArgs = 64;
constexpr int64_t kMaxUnroll = 64;
constexpr llvm::StringLiteral kWrapperModule = "opsmlir_kernel_import";
constexpr llvm::StringLiteral kAccFn = "opsmlir_acc";
constexpr llvm::StringLiteral kAccMdFn = "opsmlir_acc_md";

std::pair<fir::NameUniquer::NameKind, fir::NameUniquer::DeconstructedName> fortranName(llvm::StringRef symbol) {
  return fir::NameUniquer::deconstruct(symbol);
}

std::vector<std::string> definedModules(llvm::StringRef text) {
  std::vector<std::string> out;
  llvm::SmallVector<llvm::StringRef> lines;
  text.split(lines, '\n');
  for (llvm::StringRef line : lines) {
    std::string l = line.trim().lower();
    llvm::StringRef rest(l);
    if (!rest.consume_front("module")) continue;
    if (rest.empty() || !(rest.front() == ' ' || rest.front() == '\t')) continue;
    rest = rest.trim();
    llvm::StringRef name = rest.take_while([](char c) { return llvm::isAlnum(c) || c == '_'; });
    if (name.empty() || name == "procedure" || name == "function" || name == "subroutine") continue;
    llvm::StringRef tail = rest.drop_front(name.size()).trim();
    if (!tail.empty() && !tail.starts_with("!")) continue;
    out.push_back(name.str());
  }
  return out;
}

std::string wrapperSource(int ndim, const std::vector<std::string> &uses, llvm::StringRef kernelFile) {
  static const char *const axes[] = {"x", "y", "z"};
  std::string offsets;
  for (int d = 0; d < ndim; ++d) offsets += std::string(d ? "," : "") + axes[d];
  std::string text = "! Generated by ops-kernel-import (provider F): do not edit.\n";
  for (int n = 1; n <= kMaxArgs; ++n) {
    std::string num = std::to_string(n);
    text += "#define OPS_ACC" + num + "(" + offsets + ") " + kAccFn.str() + "(" + num + "," + offsets + ")\n";
    text += "#define OPS_ACC_MD" + num + "(d," + offsets + ") " + kAccMdFn.str() + "(" + num + ",d," + offsets + ")\n";
  }
  text += "module " + kWrapperModule.str() + "\n";
  for (const std::string &u : uses) text += "  use " + u + "\n";
  text += "  implicit none\n  interface\n";
  text += "    pure integer(4) function " + kAccFn.str() + "(n, " + offsets + ")\n";
  text += "      integer(4), value, intent(in) :: n, " + offsets + "\n";
  text += "    end function " + kAccFn.str() + "\n";
  text += "    pure integer(4) function " + kAccMdFn.str() + "(n, d, " + offsets + ")\n";
  text += "      integer(4), value, intent(in) :: n, d, " + offsets + "\n";
  text += "    end function " + kAccMdFn.str() + "\n";
  text += "  end interface\ncontains\n";
  text += "#include \"" + kernelFile.str() + "\"\n";
  text += "end module " + kWrapperModule.str() + "\n";
  return text;
}


bool runFlang(Fortran::frontend::FrontendAction &action, const std::vector<std::string> &args) {
  Fortran::frontend::CompilerInstance flang;
  flang.createDiagnostics();
  if (!flang.hasDiagnostics()) return false;

  std::vector<const char *> argv;
  for (const std::string &arg : args) argv.push_back(arg.c_str());

  auto *argDiags = new Fortran::frontend::TextDiagnosticBuffer;
  clang::DiagnosticOptions diagOpts;
  clang::DiagnosticsEngine diags(clang::DiagnosticIDs::create(), diagOpts, argDiags);
  bool ok = Fortran::frontend::CompilerInvocation::createFromArgs(flang.getInvocation(), argv, diags);
  argDiags->flushDiagnostics(flang.getDiagnostics());
  if (!ok) return false;

  llvm::SmallString<0> discard;
  flang.setOutputStream(std::make_unique<llvm::raw_svector_ostream>(discard));
  ok = flang.executeAction(action) && !flang.getDiagnostics().hasErrorOccurred();
  flang.clearOutputFiles(/*EraseFiles=*/false);
  return ok;
}

struct FParam : ParamSummary {
  Value firArg;
  std::string name;
  bool isArray = false;
  Value arg;
};

struct Ref {
  enum Kind { Bad, Param, Local, Global } kind = Bad;
  int param = -1;
  Operation *alloca = nullptr;
  std::string symbol;
  bool element = false;
  bool zeroBased = false;
  SmallVector<Value> subscripts;
  SmallVector<Value> lbounds;
  SmallVector<int64_t> extents;
};

std::optional<int64_t> constInt(Value v, int depth = 0) {
  if (!v || depth > 32) return std::nullopt;
  APInt value;
  if (matchPattern(v, m_ConstantInt(&value))) return value.getSExtValue();
  Operation *def = v.getDefiningOp();
  if (!def) return std::nullopt;
  if (isa<fir::ConvertOp, arith::IndexCastOp, arith::ExtSIOp, arith::ExtUIOp, arith::TruncIOp, fir::NoReassocOp>(def))
    return constInt(def->getOperand(0), depth + 1);
  if (isa<arith::AddIOp, arith::SubIOp, arith::MulIOp>(def)) {
    auto a = constInt(def->getOperand(0), depth + 1), b = constInt(def->getOperand(1), depth + 1);
    if (!a || !b) return std::nullopt;
    if (isa<arith::AddIOp>(def)) return *a + *b;
    if (isa<arith::SubIOp>(def)) return *a - *b;
    return *a * *b;
  }
  return std::nullopt;
}

Value stripped(Value v) {
  while (auto nr = v.getDefiningOp<fir::NoReassocOp>()) v = nr.getVal();
  return v;
}

std::string typeText(Type t) {
  std::string s;
  llvm::raw_string_ostream(s) << t;
  return s;
}

Ref describeRef(Value v, const std::vector<FParam> &params) {
  Ref r;
  for (int step = 0; step < 64; ++step) {
    if (auto ba = dyn_cast<BlockArgument>(v)) {
      for (auto [i, p] : llvm::enumerate(params))
        if (p.firArg == ba) {
          r.kind = Ref::Param;
          r.param = static_cast<int>(i);
          return r;
        }
      return r;
    }
    Operation *def = v.getDefiningOp();
    if (!def) return r;
    if (auto d = dyn_cast<fir::DeclareOp>(def)) {
      v = d.getMemref();
      continue;
    }
    if (auto c = dyn_cast<fir::ConvertOp>(def)) {
      if (!fir::isa_ref_type(c.getValue().getType())) return r;
      v = c.getValue();
      continue;
    }
    if (auto a = dyn_cast<fir::AllocaOp>(def)) {
      r.kind = Ref::Local;
      r.alloca = a;
      return r;
    }
    if (auto a = dyn_cast<fir::AddrOfOp>(def)) {
      r.kind = Ref::Global;
      r.symbol = a.getSymbol().getRootReference().getValue().str();
      return r;
    }
    auto element = [&](Value base, ValueRange subs, bool zeroBased) {
      Ref inner = describeRef(base, params);
      if (inner.kind == Ref::Bad || inner.element) return Ref();
      inner.element = true;
      inner.zeroBased = zeroBased;
      inner.subscripts.assign(subs.begin(), subs.end());
      if (auto seq = dyn_cast_or_null<fir::SequenceType>(fir::dyn_cast_ptrEleTy(base.getType())))
        for (int64_t e : seq.getShape()) inner.extents.push_back(e == fir::SequenceType::getUnknownExtent() ? -1 : e);
      return inner;
    };
    if (auto ac = dyn_cast<fir::ArrayCoorOp>(def)) {
      if (ac.getSlice() || !ac.getTypeparams().empty()) return r;
      Ref out = element(ac.getMemref(), ac.getIndices(), false);
      if (Value shape = ac.getShape())
        if (auto ss = shape.getDefiningOp<fir::ShapeShiftOp>())
          for (auto [i, pair] : llvm::enumerate(ss.getPairs()))
            if (i % 2 == 0) out.lbounds.push_back(pair);
      return out;
    }
    if (auto co = dyn_cast<fir::CoordinateOp>(def)) {
      if (co.getFieldIndicesAttr()) return r;
      return element(co.getRef(), co.getCoor(), true);
    }
    return r;
  }
  return r;
}

fir::CallOp accCall(Value v) {
  for (int step = 0; step < 8 && v; ++step) {
    Operation *def = v.getDefiningOp();
    if (!def) return {};
    if (auto call = dyn_cast<fir::CallOp>(def)) {
      if (!call.getCallee()) return {};
      std::string name = fortranName(call.getCallee()->getRootReference().getValue()).second.name;
      return name == kAccFn || name == kAccMdFn ? call : fir::CallOp();
    }
    if (isa<fir::ConvertOp, arith::IndexCastOp, arith::ExtSIOp>(def)) v = def->getOperand(0);
    else return {};
  }
  return {};
}

class FIRKernelWalker {
public:
  FIRKernelWalker(MLIRContext &ctx, ArrayRef<ModuleOp> firModules, func::FuncOp firFn, std::vector<FParam> &params,
                  int rank)
      : b(&ctx), loc(b.getUnknownLoc()), firModules(firModules), firFn(firFn), params(params), rank(rank) {}

  OpBuilder &builder() { return b; }
  bool ok() const { return failure.empty(); }
  const std::string &error() const { return failure; }
  const std::vector<std::string> &warnings() const { return warningList; }
  const std::set<ConstUse> &constUses() const { return consts; }
  unsigned idxAxesRead() const { return idxAxes; }
  unsigned droppedPrintf() const { return dropped; }

  void run() { walkBlock(firFn.getBody().front(), nullptr); }

private:
  OpBuilder b;
  Location loc;
  SmallVector<ModuleOp> firModules;
  func::FuncOp firFn;
  std::vector<FParam> &params;
  int rank;

  std::string failure;
  std::vector<std::string> warningList;
  std::set<ConstUse> consts;
  unsigned idxAxes = 0;
  unsigned dropped = 0;

  DenseMap<Value, Value> values;
  DenseMap<Value, int> tainted;
  DenseSet<Value> ioValues;

  using SlotKey = std::pair<Operation *, int64_t>;
  DenseMap<SlotKey, Value> slots;
  DenseMap<Operation *, unsigned> allocaOrder;

  Ref describe(Value v) { return describeRef(v, params); }

  static std::string where(Operation *op) {
    if (!op) return "";
    if (auto fl = op->getLoc()->findInstanceOf<FileLineColLoc>())
      return (llvm::sys::path::filename(fl.getFilename().getValue()) + ":" + llvm::Twine(fl.getLine()) + ": ").str();
    return "";
  }
  Value fail(const llvm::Twine &message, Operation *at = nullptr) {
    if (failure.empty()) failure = where(at) + message.str();
    return {};
  }
  void warn(const llvm::Twine &message, Operation *at) { warningList.push_back(where(at) + message.str()); }

  Type modelType(Type t) {
    if (isa<fir::LogicalType>(t)) return b.getI1Type();
    if (t.isIntOrIndexOrFloat()) return t;
    return {};
  }
  Value zeroOf(Type t) {
    if (auto ft = dyn_cast<FloatType>(t)) return arith::ConstantOp::create(b, loc, b.getFloatAttr(ft, 0.0));
    if (t.isIndex()) return arith::ConstantIndexOp::create(b, loc, 0);
    return arith::ConstantOp::create(b, loc, b.getIntegerAttr(t, 0));
  }
  Value constI32(int64_t v) { return arith::ConstantOp::create(b, loc, b.getI32IntegerAttr(static_cast<int32_t>(v))); }

  Value cast(Value v, Type to, Operation *at) {
    if (!v) return {};
    Type from = v.getType();
    if (from == to) return v;
    auto fromF = dyn_cast<FloatType>(from), toF = dyn_cast<FloatType>(to);
    bool fromI = from.isIntOrIndex(), toI = to.isIntOrIndex();
    if (fromF && toF)
      return fromF.getWidth() < toF.getWidth() ? Value(arith::ExtFOp::create(b, loc, to, v))
                                               : Value(arith::TruncFOp::create(b, loc, to, v));
    if (fromI && toF) {
      if (from.isIndex()) v = arith::IndexCastOp::create(b, loc, b.getI64Type(), v);
      return from.isInteger(1) ? Value(arith::UIToFPOp::create(b, loc, to, v))
                               : Value(arith::SIToFPOp::create(b, loc, to, v));
    }
    if (fromF && toI) {
      if (to.isInteger(1)) return arith::CmpFOp::create(b, loc, arith::CmpFPredicate::UNE, v, zeroOf(from));
      if (to.isIndex()) return arith::IndexCastOp::create(b, loc, to, arith::FPToSIOp::create(b, loc, b.getI64Type(), v));
      return arith::FPToSIOp::create(b, loc, to, v);
    }
    if (fromI && toI) {
      if (to.isInteger(1)) return arith::CmpIOp::create(b, loc, arith::CmpIPredicate::ne, v, zeroOf(from));
      if (from.isIndex() || to.isIndex()) return arith::IndexCastOp::create(b, loc, to, v);
      if (from.isInteger(1)) return arith::ExtUIOp::create(b, loc, to, v);
      return from.getIntOrFloatBitWidth() < to.getIntOrFloatBitWidth() ? Value(arith::ExtSIOp::create(b, loc, to, v))
                                                                      : Value(arith::TruncIOp::create(b, loc, to, v));
    }
    return fail("unsupported conversion from " + typeText(from) + " to " + typeText(to), at);
  }

  Value mapped(Value v, Operation *at) {
    if (auto it = values.find(v); it != values.end()) return it->second;
    if (tainted.count(v))
      return fail("the value of a reduction argument is read (only the updates r = r + x, r = r - x, "
                  "r = min(r, x) and r = max(r, x) are supported)",
                  at);
    if (ioValues.count(v)) return fail("the result of an I/O statement is used", at);
    if (accCall(v)) return fail("OPS_ACCn/OPS_ACC_MDn is used outside the subscript of its argument", at);
    return fail("a value of the kernel has no translation (unsupported construct)", at);
  }

  Type slotType(Operation *alloca) {
    Type in = llvm::cast<fir::AllocaOp>(alloca).getInType();
    if (auto seq = dyn_cast<fir::SequenceType>(in)) in = seq.getEleTy();
    return modelType(in);
  }
  Value current(SlotKey k) {
    if (auto it = slots.find(k); it != slots.end() && it->second) return it->second;
    return zeroOf(slotType(k.first));
  }

  std::optional<int64_t> linearIndex(const Ref &r, ArrayRef<std::optional<int64_t>> subs) {
    int64_t lin = 0, scale = 1;
    for (size_t i = 0; i < subs.size(); ++i) {
      if (!subs[i]) return std::nullopt;
      int64_t lb = r.zeroBased ? 0 : 1;
      if (i < r.lbounds.size()) {
        auto l = constInt(r.lbounds[i]);
        if (!l) return std::nullopt;
        lb = *l;
      }
      lin += (*subs[i] - lb) * scale;
      int64_t extent = i < r.extents.size() ? r.extents[i] : -1;
      if (i + 1 < subs.size() && extent < 0) return std::nullopt;
      scale *= extent < 0 ? 1 : extent;
    }
    return lin;
  }
  SmallVector<std::optional<int64_t>> translatedSubscripts(const Ref &r, Operation *at) {
    SmallVector<std::optional<int64_t>> out;
    for (Value s : r.subscripts) {
      Value t = mapped(s, at);
      out.push_back(t ? constInt(t) : std::nullopt);
    }
    return out;
  }
  std::optional<SlotKey> slotKey(const Ref &r, Operation *at) {
    if (!slotType(r.alloca)) {
      fail("a local variable of an unsupported type (only real, integer and logical scalars and arrays)", at);
      return std::nullopt;
    }
    if (!r.element) return SlotKey{r.alloca, -1};
    auto subs = translatedSubscripts(r, at);
    if (!ok()) return std::nullopt;
    auto lin = linearIndex(r, subs);
    if (!lin) {
      fail("a local array is subscripted by a value that is not a compile-time constant", at);
      return std::nullopt;
    }
    return SlotKey{r.alloca, *lin};
  }

  std::vector<SlotKey> assignedSlots(Region &region) {
    std::set<std::pair<unsigned, int64_t>> ordered;
    DenseMap<unsigned, Operation *> byOrder;
    region.walk([&](fir::StoreOp store) {
      Ref r = describe(store.getMemref());
      if (r.kind != Ref::Local || !slotType(r.alloca)) return;
      unsigned order = allocaOrder.try_emplace(r.alloca, allocaOrder.size()).first->second;
      byOrder[order] = r.alloca;
      if (!r.element) {
        ordered.insert({order, -1});
        return;
      }
      SmallVector<std::optional<int64_t>> subs;
      for (Value s : r.subscripts) {
        auto it = values.find(s);
        subs.push_back(it != values.end() ? constInt(it->second) : constInt(s));
      }
      if (auto lin = linearIndex(r, subs)) {
        ordered.insert({order, *lin});
        return;
      }
      auto seq = dyn_cast<fir::SequenceType>(llvm::cast<fir::AllocaOp>(r.alloca).getInType());
      int64_t total = 1;
      for (int64_t e : seq.getShape()) total *= e < 0 ? 0 : e;
      for (int64_t i = 0; i < std::min<int64_t>(total, 4096); ++i) ordered.insert({order, i});
    });
    std::vector<SlotKey> out;
    for (auto [order, elem] : ordered) out.push_back({byOrder[order], elem});
    return out;
  }

  void walkBlock(Block &block, SmallVectorImpl<Value> *results) {
    for (Operation &op : block) {
      if (!ok()) return;
      if (auto res = dyn_cast<fir::ResultOp>(op)) {
        if (results)
          for (Value v : res.getOperands()) results->push_back(mapped(v, &op));
        continue;
      }
      translate(&op);
    }
  }

  void translate(Operation *op) {
    if (isa<fir::DummyScopeOp, fir::ShapeOp, fir::ShapeShiftOp, fir::DeclareOp, fir::AddrOfOp, fir::ArrayCoorOp,
            fir::CoordinateOp>(op))
      return;
    if (isa<fir::AllocaOp>(op)) {
      allocaOrder.try_emplace(op, allocaOrder.size());
      return;
    }
    if (isa<func::ReturnOp>(op)) {
      if (op->getNumOperands() != 0) fail("the kernel is a function; OPS kernels are subroutines", op);
      return;
    }
    if (auto load = dyn_cast<fir::LoadOp>(op)) return translateLoad(load);
    if (auto store = dyn_cast<fir::StoreOp>(op)) return translateStore(store);
    if (auto convert = dyn_cast<fir::ConvertOp>(op)) return translateConvert(convert);
    if (auto nr = dyn_cast<fir::NoReassocOp>(op)) {
      if (propagateTaint(op)) return;
      if (Value v = mapped(nr.getVal(), op)) values[nr.getResult()] = v;
      return;
    }
    if (auto call = dyn_cast<fir::CallOp>(op)) return translateCall(call);
    if (auto ifOp = dyn_cast<fir::IfOp>(op)) return translateIf(ifOp);
    if (auto loop = dyn_cast<fir::DoLoopOp>(op)) return translateDoLoop(loop);
    if (isa<fir::ZeroOp, fir::EmboxOp>(op)) {
      for (Value r : op->getResults()) ioValues.insert(r);
      return;
    }
    if (auto undef = dyn_cast<fir::UndefOp>(op)) {
      if (Type t = modelType(undef.getType())) values[undef.getResult()] = zeroOf(t);
      else fail("an undefined value of an unsupported type", op);
      return;
    }
    if (isa<fir::LogicalAndOp, fir::LogicalOrOp, fir::EqvOp, fir::NeqvOp>(op)) return translateLogical(op);
    if (op->getDialect() && op->getDialect()->getNamespace() == "arith") return cloneMapped(op);
    if (op->getDialect() && op->getDialect()->getNamespace() == "math") return translateMath(op);
    fail("unsupported operation '" + op->getName().getStringRef() + "'", op);
  }

  bool propagateTaint(Operation *op) {
    for (Value v : op->getOperands())
      if (auto it = tainted.find(v); it != tainted.end()) {
        int param = it->second;
        for (Value r : op->getResults()) tainted[r] = param;
        return true;
      }
    return false;
  }

  void cloneMapped(Operation *op) {
    if (propagateTaint(op)) return;
    IRMapping mapping;
    for (Value v : op->getOperands()) {
      Value m = mapped(v, op);
      if (!m) return;
      mapping.map(v, m);
    }
    Operation *cloned = b.clone(*op, mapping);
    cloned->setLoc(loc);
    // flang marks floating point operations `contract`; the JIT decides about contraction itself (OPS_JIT_FMA).
    if (auto fm = dyn_cast<arith::ArithFastMathInterface>(cloned))
      cloned->setAttr(fm.getFastMathAttrName(), arith::FastMathFlagsAttr::get(b.getContext(), arith::FastMathFlags::none));
    for (auto [from, to] : llvm::zip(op->getResults(), cloned->getResults())) values[from] = to;
  }

  void translateMath(Operation *op) {
    if (propagateTaint(op)) return;
    if (isa<math::FPowIOp, math::IPowIOp>(op)) {
      Value base = mapped(op->getOperand(0), op), exp = mapped(op->getOperand(1), op);
      if (!base || !exp) return;
      Type t = base.getType();
      bool isFloat = isa<FloatType>(t);
      if (auto n = constInt(exp); n && *n >= -8 && *n <= 8 && (isFloat || *n >= 0)) {
        Value one = isFloat ? Value(arith::ConstantOp::create(b, loc, b.getFloatAttr(t, 1.0)))
                            : Value(arith::ConstantOp::create(b, loc, b.getIntegerAttr(t, 1)));
        Value acc = one;
        for (int64_t i = 0; i < std::abs(*n); ++i)
          acc = i == 0 ? base
                       : (isFloat ? Value(arith::MulFOp::create(b, loc, acc, base)) : Value(arith::MulIOp::create(b, loc, acc, base)));
        if (*n < 0) acc = arith::DivFOp::create(b, loc, one, acc);
        values[op->getResult(0)] = acc;
        return;
      }
      if (!isFloat) {
        fail("integer ** integer with an exponent that is not a small constant", op);
        return;
      }
      values[op->getResult(0)] = math::PowFOp::create(b, loc, base, cast(exp, t, op));
      return;
    }
    if (!isa<math::SqrtOp, math::AbsFOp, math::AbsIOp, math::ExpOp, math::Exp2Op, math::LogOp, math::Log2Op,
             math::Log10Op, math::SinOp, math::CosOp, math::TanOp, math::AsinOp, math::AcosOp, math::AtanOp,
             math::SinhOp, math::CoshOp, math::TanhOp, math::FloorOp, math::CeilOp, math::RoundOp, math::TruncOp,
             math::CbrtOp, math::ErfOp, math::PowFOp, math::Atan2Op, math::CopySignOp>(op)) {
      fail("unsupported intrinsic ('" + op->getName().getStringRef() + "')", op);
      return;
    }
    cloneMapped(op);
  }

  void translateLogical(Operation *op) {
    if (propagateTaint(op)) return;
    Value l = mapped(op->getOperand(0), op), r = mapped(op->getOperand(1), op);
    if (!l || !r) return;
    l = cast(l, b.getI1Type(), op);
    r = cast(r, b.getI1Type(), op);
    Value v;
    if (isa<fir::LogicalAndOp>(op)) v = arith::AndIOp::create(b, loc, l, r);
    else if (isa<fir::LogicalOrOp>(op)) v = arith::OrIOp::create(b, loc, l, r);
    else if (isa<fir::NeqvOp>(op)) v = arith::XOrIOp::create(b, loc, l, r);
    else v = arith::CmpIOp::create(b, loc, arith::CmpIPredicate::eq, l, r);
    values[op->getResult(0)] = v;
  }

  void translateConvert(fir::ConvertOp convert) {
    Value in = convert.getValue();
    if (ioValues.count(in)) {
      ioValues.insert(convert.getResult());
      return;
    }
    if (fir::isa_ref_type(in.getType()) || accCall(in)) return;
    if (propagateTaint(convert)) return;
    Type to = modelType(convert.getType());
    if (!to) {
      fail("unsupported conversion to " + typeText(convert.getType()), convert);
      return;
    }
    Value v = mapped(in, convert);
    if (!v) return;
    if (Value c = cast(v, to, convert)) values[convert.getResult()] = c;
  }

  static std::string mathFunction(llvm::StringRef callee) {
    std::string name = callee.str();
    llvm::StringRef bare(name);
    bare.consume_front("_Fortran");
    if (bare.size() > 1 && bare.front() == 'A' && llvm::isUpper(bare[1])) bare = bare.drop_front();
    std::string fn = bare.lower();
    if (fn == "modreal4" || fn == "modreal8") return "fmod";
    auto known = [](llvm::StringRef f) {
      return llvm::StringSwitch<bool>(f)
          .Cases({"sin", "cos", "tan", "asin", "acos", "atan", "sinh", "cosh", "tanh", "exp", "log", "log10"}, true)
          .Cases({"sqrt", "fabs", "cbrt", "erf", "floor", "ceil", "pow", "atan2", "fmod", "copysign"}, true)
          .Default(false);
    };
    if (known(fn)) return fn;
    if (fn.size() > 1 && (fn.back() == 'f' || fn.back() == 'l') && known(llvm::StringRef(fn).drop_back()))
      return fn.substr(0, fn.size() - 1);
    return "";
  }

  void translateCall(fir::CallOp call) {
    if (call.getNumResults() == 1 && accCall(call.getResult(0))) return;
    if (!call.getCallee()) {
      fail("indirect call", call);
      return;
    }
    llvm::StringRef callee = call.getCallee()->getRootReference().getValue();
    if (callee.starts_with("_FortranAio")) {
      if (callee.starts_with("_FortranAioBegin")) {
        ++dropped;
        warn("an I/O statement is dropped", call);
      }
      for (Value r : call.getResults()) ioValues.insert(r);
      return;
    }
    for (Value a : call.getArgs())
      if (tainted.count(a)) {
        mapped(a, call);
        return;
      }
    std::string fn = mathFunction(callee);
    std::string name = fortranName(callee).second.name;
    if (fn.empty() || call.getNumResults() != 1) {
      fail("call to '" + llvm::Twine(name.empty() ? callee.str() : name) +
               "' (only intrinsic math functions are supported; helper procedures are not)",
           call);
      return;
    }
    SmallVector<Value> args;
    for (Value a : call.getArgs()) {
      Value m = mapped(a, call);
      if (!m) return;
      args.push_back(m);
    }
    Type t = call.getResult(0).getType();
    if (!isa<FloatType>(t)) {
      fail("call to '" + llvm::Twine(fn) + "' with a result that is not real", call);
      return;
    }
    for (Value &a : args) a = cast(a, t, call);
    auto un = [&](auto tag) -> Value {
      using Op = decltype(tag);
      return Op::create(b, loc, args[0]);
    };
    Value v;
    if (args.size() == 1) {
      if (fn == "sin") v = un(math::SinOp());
      else if (fn == "cos") v = un(math::CosOp());
      else if (fn == "tan") v = un(math::TanOp());
      else if (fn == "asin") v = un(math::AsinOp());
      else if (fn == "acos") v = un(math::AcosOp());
      else if (fn == "atan") v = un(math::AtanOp());
      else if (fn == "sinh") v = un(math::SinhOp());
      else if (fn == "cosh") v = un(math::CoshOp());
      else if (fn == "tanh") v = un(math::TanhOp());
      else if (fn == "exp") v = un(math::ExpOp());
      else if (fn == "log") v = un(math::LogOp());
      else if (fn == "log10") v = un(math::Log10Op());
      else if (fn == "sqrt") v = un(math::SqrtOp());
      else if (fn == "fabs") v = un(math::AbsFOp());
      else if (fn == "cbrt") v = un(math::CbrtOp());
      else if (fn == "erf") v = un(math::ErfOp());
      else if (fn == "floor") v = un(math::FloorOp());
      else if (fn == "ceil") v = un(math::CeilOp());
    } else if (args.size() == 2) {
      if (fn == "pow") v = math::PowFOp::create(b, loc, args[0], args[1]);
      else if (fn == "atan2") v = math::Atan2Op::create(b, loc, args[0], args[1]);
      else if (fn == "fmod") v = arith::RemFOp::create(b, loc, args[0], args[1]);
      else if (fn == "copysign") v = math::CopySignOp::create(b, loc, args[0], args[1]);
    }
    if (!v) {
      fail("call to '" + llvm::Twine(fn) + "' with " + llvm::Twine(args.size()) + " arguments", call);
      return;
    }
    values[call.getResult(0)] = v;
  }

  void translateLoad(fir::LoadOp load) {
    Ref r = describe(load.getMemref());
    Type t = modelType(load.getType());
    if (r.kind == Ref::Bad || !t) {
      fail("load from an unsupported location (kernels may read their arguments, locals and module variables)", load);
      return;
    }
    if (r.kind == Ref::Local) {
      if (auto key = slotKey(r, load)) values[load.getResult()] = cast(current(*key), t, load);
      return;
    }
    if (r.kind == Ref::Global) {
      if (Value v = emitGlobal(r, t, load)) values[load.getResult()] = v;
      return;
    }
    FParam &p = params[r.param];
    switch (p.kind) {
    case ParamSummary::Acc:
      if (Value v = emitAccess(r, load, Value())) values[load.getResult()] = cast(v, t, load);
      return;
    case ParamSummary::Red: {
      if (r.element) {
        auto subs = translatedSubscripts(r, load);
        if (!ok()) return;
        auto lin = linearIndex(r, subs);
        if (!lin || *lin != 0) {
          fail("the reduction argument '" + p.name + "' is subscripted with something else than its first element", load);
          return;
        }
      }
      tainted[load.getResult()] = r.param;
      return;
    }
    case ParamSummary::Gbl: {
      int64_t k = 0;
      if (r.element) {
        auto subs = translatedSubscripts(r, load);
        if (!ok()) return;
        auto lin = linearIndex(r, subs);
        if (!lin || *lin < 0) {
          fail("the global argument '" + p.name + "' is subscripted by a value that is not a compile-time constant", load);
          return;
        }
        k = *lin;
      }
      p.gblDim = std::max(p.gblDim, k + 1);
      values[load.getResult()] = cast(GblReadOp::create(b, loc, p.elem, p.arg, b.getI64IntegerAttr(k)), t, load);
      return;
    }
    case ParamSummary::Idx: {
      SmallVector<std::optional<int64_t>> subs;
      if (r.element) subs = translatedSubscripts(r, load);
      if (!ok()) return;
      auto lin = r.element ? linearIndex(r, subs) : std::optional<int64_t>(0);
      if (!lin || *lin < 0 || *lin >= rank) {
        fail("the index argument is subscripted by a value that is not a constant between 1 and " + llvm::Twine(rank), load);
        return;
      }
      idxAxes |= 1u << *lin;
      // OPS Fortran's index is one-based: idx(d) is the global index in dimension d plus one.
      Value idx = IndexOp::create(b, loc, b.getI32Type(), b.getI64IntegerAttr(*lin));
      values[load.getResult()] = cast(arith::AddIOp::create(b, loc, idx, constI32(1)), t, load);
      return;
    }
    }
  }

  void translateStore(fir::StoreOp store) {
    Ref r = describe(store.getMemref());
    if (r.kind == Ref::Param && params[r.param].kind == ParamSummary::Red) return storeReduction(r, store);
    if (tainted.count(store.getValue())) {
      mapped(store.getValue(), store);
      return;
    }
    if (r.kind == Ref::Local) {
      auto key = slotKey(r, store);
      if (!key) return;
      if (Value v = mapped(store.getValue(), store)) slots[*key] = cast(v, slotType(key->first), store);
      return;
    }
    if (r.kind == Ref::Param && params[r.param].kind == ParamSummary::Acc) {
      if (Value v = mapped(store.getValue(), store)) emitAccess(r, store, v);
      return;
    }
    if (r.kind == Ref::Param)
      fail("assignment to the " + llvm::Twine(params[r.param].kind == ParamSummary::Gbl ? "global" : "index") +
               " argument '" + params[r.param].name + "'",
           store);
    else if (r.kind == Ref::Global)
      fail("assignment to a module variable", store);
    else
      fail("store to an unsupported location", store);
  }

  Value emitAccess(const Ref &r, Operation *at, Value value) {
    FParam &p = params[r.param];
    fir::CallOp call = r.element && r.subscripts.size() == 1 ? accCall(r.subscripts[0]) : fir::CallOp();
    if (!call)
      return fail("the dat argument '" + p.name + "' is subscripted without OPS_ACC" + llvm::Twine(r.param + 1) + "(...)", at);
    bool md = fortranName(call.getCallee()->getRootReference().getValue()).second.name == kAccMdFn;
    SmallVector<Value> args;
    for (Value a : call.getArgs()) {
      Value m = mapped(a, at);
      if (!m) return {};
      args.push_back(m);
    }
    auto n = constInt(args[0]);
    if (!n || *n != r.param + 1)
      return fail("OPS_ACC" + llvm::Twine(n.value_or(0)) + " subscripts argument " + llvm::Twine(r.param + 1) + " ('" +
                      p.name + "'): OPS_ACCn must subscript the n-th argument",
                  at);
    int64_t comp = 0;
    unsigned first = 1;
    if (md) {
      auto d = constInt(args[1]);
      if (!d || *d < 1)
        return fail("the component of OPS_ACC_MD" + llvm::Twine(*n) + " is not a positive compile-time constant", at);
      comp = *d - 1; // components are one-based in Fortran
      first = 2;
    }
    p.ncomp = std::max(p.ncomp, comp + 1);
    SmallVector<int64_t> offsets;
    bool constant = true;
    for (unsigned i = first; i < args.size(); ++i) {
      if (auto c = constInt(args[i])) offsets.push_back(*c);
      else constant = false;
    }
    if (value) {
      if (p.isConst) return fail("assignment to the intent(in) dat argument '" + p.name + "'", at);
      if (!constant) return fail("write to a dat at an offset that is not a compile-time constant", at);
      p.writes.insert(std::vector<int64_t>(offsets.begin(), offsets.end()));
      WriteOp::create(b, loc, p.arg, b.getDenseI64ArrayAttr(offsets), cast(value, p.elem, at), b.getI64IntegerAttr(comp));
      return value;
    }
    if (constant) {
      p.reads.insert(std::vector<int64_t>(offsets.begin(), offsets.end()));
      return ReadOp::create(b, loc, p.elem, p.arg, b.getDenseI64ArrayAttr(offsets), b.getI64IntegerAttr(comp));
    }
    p.dynamicRead = true;
    SmallVector<Value> dyn;
    for (unsigned i = first; i < args.size(); ++i) dyn.push_back(cast(args[i], b.getI32Type(), at));
    return ReadDynOp::create(b, loc, p.elem, p.arg, dyn, b.getI64IntegerAttr(comp));
  }

  void storeReduction(const Ref &r, fir::StoreOp store) {
    FParam &p = params[r.param];
    auto isR = [&](Value v) {
      v = stripped(v);
      auto it = tainted.find(v);
      return it != tainted.end() && it->second == r.param && v.getDefiningOp<fir::LoadOp>();
    };
    auto clean = [&](Value v) { return !tainted.count(v); };
    Value v = stripped(store.getValue());
    Value contribution;
    bool negate = false;
    std::string kind;
    Operation *def = v.getDefiningOp();
    if (clean(v)) {
      contribution = v;
    } else if (def && isa<arith::AddFOp, arith::AddIOp>(def)) {
      if (isR(def->getOperand(0)) && clean(def->getOperand(1))) contribution = def->getOperand(1);
      else if (isR(def->getOperand(1)) && clean(def->getOperand(0))) contribution = def->getOperand(0);
      kind = "add";
    } else if (def && isa<arith::SubFOp, arith::SubIOp>(def)) {
      if (isR(def->getOperand(0)) && clean(def->getOperand(1))) contribution = def->getOperand(1);
      negate = true;
      kind = "add";
    } else if (def && isa<arith::MinimumFOp, arith::MinNumFOp, arith::MinSIOp, arith::MaximumFOp, arith::MaxNumFOp,
                          arith::MaxSIOp>(def)) {
      if (isR(def->getOperand(0)) && clean(def->getOperand(1))) contribution = def->getOperand(1);
      else if (isR(def->getOperand(1)) && clean(def->getOperand(0))) contribution = def->getOperand(0);
      kind = isa<arith::MinimumFOp, arith::MinNumFOp, arith::MinSIOp>(def) ? "min" : "max";
    } else if (auto sel = dyn_cast_or_null<arith::SelectOp>(def)) {
      // MIN/MAX as flang spells them: select(cmp(p, q), x, y) with {x, y} = {p, q} = {r, other}.
      Operation *cmp = sel.getCondition().getDefiningOp();
      Value x = stripped(sel.getTrueValue()), y = stripped(sel.getFalseValue());
      std::optional<bool> less;
      if (auto c = dyn_cast_or_null<arith::CmpFOp>(cmp)) {
        using P = arith::CmpFPredicate;
        P pr = c.getPredicate();
        if (pr == P::OLT || pr == P::OLE || pr == P::ULT || pr == P::ULE) less = true;
        if (pr == P::OGT || pr == P::OGE || pr == P::UGT || pr == P::UGE) less = false;
      } else if (auto c = dyn_cast_or_null<arith::CmpIOp>(cmp)) {
        using P = arith::CmpIPredicate;
        P pr = c.getPredicate();
        if (pr == P::slt || pr == P::sle) less = true;
        if (pr == P::sgt || pr == P::sge) less = false;
      }
      if (less) {
        Value pv = stripped(cmp->getOperand(0)), qv = stripped(cmp->getOperand(1));
        bool same = x == pv && y == qv, swapped = x == qv && y == pv;
        Value other = isR(x) ? y : (isR(y) ? x : Value());
        if ((same || swapped) && other && clean(other)) {
          contribution = other;
          kind = (same == *less) ? "min" : "max";
        }
      }
    }
    if (!contribution) {
      fail("unsupported update of the reduction argument '" + p.name +
               "' (supported: r = r + x, r = r - x, r = min(r, x), r = max(r, x) and r = x)",
           store);
      return;
    }
    Value c = mapped(contribution, store);
    if (!c) return;
    c = cast(c, p.elem, store);
    if (negate)
      c = isa<FloatType>(c.getType()) ? Value(arith::NegFOp::create(b, loc, c))
                                      : Value(arith::SubIOp::create(b, loc, zeroOf(c.getType()), c));
    if (!kind.empty()) {
      if (!p.kindHint.empty() && p.kindHint != kind) {
        fail("a reduction that is updated as both " + llvm::Twine(p.kindHint) + " and " + kind, store);
        return;
      }
      p.kindHint = kind;
    } else {
      p.style = "assign";
    }
    ReduceOp::create(b, loc, p.arg, c);
  }

  Value emitGlobal(const Ref &r, Type t, Operation *at) {
    auto [kind, parts] = fortranName(r.symbol);
    fir::GlobalOp global;
    for (ModuleOp m : firModules)
      if (auto g = m.lookupSymbol<fir::GlobalOp>(r.symbol)) {
        if (!global) global = g;
        if (g.getInitValAttr() || !g.getRegion().empty()) {
          global = g;
          break;
        }
      }
    SmallVector<std::optional<int64_t>> subs;
    if (r.element) subs = translatedSubscripts(r, at);
    if (!ok()) return {};
    if (global && global.getConstant()) {
      auto lin = r.element ? linearIndex(r, subs) : std::optional<int64_t>(0);
      if (!lin)
        return fail("the parameter array '" + parts.name + "' is subscripted by a value that is not a compile-time constant", at);
      if (Attribute init = global.getInitValAttr()) {
        Attribute elem = init;
        if (auto dense = dyn_cast<DenseElementsAttr>(init)) {
          if (*lin < 0 || *lin >= dense.getNumElements()) return fail("subscript out of the bounds of '" + parts.name + "'", at);
          elem = dense.getValues<Attribute>()[*lin];
        }
        if (auto f = dyn_cast<FloatAttr>(elem)) return cast(arith::ConstantOp::create(b, loc, f), t, at);
        if (auto i = dyn_cast<IntegerAttr>(elem)) return cast(arith::ConstantOp::create(b, loc, i), t, at);
      }
      if (!r.element && !global.getRegion().empty())
        for (Operation &op : global.getRegion().front())
          if (auto c = dyn_cast<arith::ConstantOp>(op)) return cast(arith::ConstantOp::create(b, loc, c.getValue()), t, at);
      return fail("cannot fold the parameter '" + parts.name + "'", at);
    }
    if (kind != fir::NameUniquer::NameKind::VARIABLE || parts.modules.empty() || !parts.procs.empty())
      return fail("'" + parts.name + "' is not a module variable (kernels may read module variables declared with "
                  "ops_decl_const)",
                  at);
    if (t.isInteger(1) || !isSupportedElementType(t))
      return fail("module variable '" + parts.name + "' has an unsupported type (" + typeText(t) + ")", at);
    int64_t size = t.getIntOrFloatBitWidth() / 8;
    ConstUse use;
    use.name = parts.name;
    use.elem = t;
    Value index;
    if (r.element) {
      if (auto lin = linearIndex(r, subs)) {
        use.offset = *lin * size;
      } else if (r.subscripts.size() == 1) {
        Value s = mapped(r.subscripts[0], at);
        if (!s) return {};
        int64_t lb = r.zeroBased ? 0 : 1;
        if (!r.lbounds.empty()) {
          auto l = constInt(r.lbounds[0]);
          if (!l) return fail("module array '" + parts.name + "' with a lower bound that is not a constant", at);
          lb = *l;
        }
        index = arith::SubIOp::create(b, loc, cast(s, b.getI32Type(), at), constI32(lb));
        use.stride = size;
        use.dynamicIndex = true;
      } else {
        return fail("module array '" + parts.name + "' of rank > 1 subscripted by values that are not compile-time constants", at);
      }
    }
    consts.insert(use);
    return ConstRefOp::create(b, loc, t, FlatSymbolRefAttr::get(b.getContext(), use.name),
                              b.getI64IntegerAttr(use.offset), index, b.getI64IntegerAttr(use.stride));
  }

  void translateIf(fir::IfOp ifOp) {
    if (tainted.count(ifOp.getCondition())) {
      fail("a condition tests the value of a reduction argument (write the update as r = min(r, x) or r = max(r, x))", ifOp);
      return;
    }
    Value cond = mapped(ifOp.getCondition(), ifOp);
    if (!cond) return;
    cond = cast(cond, b.getI1Type(), ifOp);
    std::vector<SlotKey> keys;
    for (Region *region : {&ifOp.getThenRegion(), &ifOp.getElseRegion()})
      for (SlotKey k : assignedSlots(*region))
        if (llvm::find(keys, k) == keys.end()) keys.push_back(k);
    SmallVector<Type> types;
    for (Value res : ifOp.getResults()) {
      Type t = modelType(res.getType());
      if (!t) {
        fail("an IF with a result of an unsupported type", ifOp);
        return;
      }
      types.push_back(t);
    }
    for (SlotKey k : keys) types.push_back(slotType(k.first));

    auto scfIf = scf::IfOp::create(b, loc, types, cond, /*withElseRegion=*/true);
    auto saved = slots;
    for (int branch = 0; branch < 2 && ok(); ++branch) {
      Region &region = branch == 0 ? ifOp.getThenRegion() : ifOp.getElseRegion();
      Block *target = branch == 0 ? &scfIf.getThenRegion().front() : &scfIf.getElseRegion().front();
      OpBuilder::InsertionGuard guard(b);
      if (!target->empty() && target->back().hasTrait<OpTrait::IsTerminator>()) target->back().erase();
      b.setInsertionPointToEnd(target);
      slots = saved;
      SmallVector<Value> yielded;
      if (!region.empty()) walkBlock(region.front(), &yielded);
      if (!ok()) break;
      SmallVector<Value> out;
      for (auto [i, v] : llvm::enumerate(yielded)) out.push_back(cast(v, types[i], ifOp));
      for (SlotKey k : keys) out.push_back(current(k));
      if (out.size() != types.size()) {
        fail("an IF whose branches do not produce the same values", ifOp);
        break;
      }
      scf::YieldOp::create(b, loc, out);
    }
    slots = saved;
    if (!ok()) return;
    b.setInsertionPointAfter(scfIf);
    unsigned n = ifOp.getNumResults();
    for (unsigned i = 0; i < n; ++i) values[ifOp.getResult(i)] = scfIf.getResult(i);
    for (auto [i, k] : llvm::enumerate(keys)) slots[k] = scfIf.getResult(n + i);
  }

  static bool subscriptsSomething(Region &region) {
    bool found = false;
    region.walk([&](Operation *op) {
      if (isa<fir::ArrayCoorOp, fir::CoordinateOp>(op)) found = true;
    });
    return found;
  }

  void translateDoLoop(fir::DoLoopOp loop) {
    if (!loop.getReduceOperands().empty() || loop.getFinalValue()) {
      fail("unsupported form of DO loop", loop);
      return;
    }
    Value lb = mapped(loop.getLowerBound(), loop), ub = mapped(loop.getUpperBound(), loop),
          step = mapped(loop.getStep(), loop);
    if (!lb || !ub || !step) return;
    SmallVector<Value> inits;
    for (Value v : loop.getInitArgs()) {
      Value m = mapped(v, loop);
      if (!m) return;
      inits.push_back(m);
    }
    Block &body = loop.getRegion().front();
    Value iv = body.getArgument(0);
    auto cl = constInt(lb), cu = constInt(ub), cs = constInt(step);

    if (cl && cu && cs && *cs != 0 && subscriptsSomething(loop.getRegion())) {
      int64_t trip = std::max<int64_t>(0, (*cu - *cl + *cs) / *cs);
      if (trip <= kMaxUnroll) {
        SmallVector<Value> iter = inits;
        for (int64_t k = 0; k < trip && ok(); ++k) {
          values[iv] = arith::ConstantIndexOp::create(b, loc, *cl + k * *cs);
          for (auto [i, v] : llvm::enumerate(iter)) values[body.getArgument(1 + i)] = v;
          SmallVector<Value> next;
          walkBlock(body, &next);
          if (!ok()) return;
          iter = next;
        }
        for (auto [i, r] : llvm::enumerate(loop.getResults())) values[r] = iter[i];
        return;
      }
    }
    if (!cs || *cs <= 0) {
      fail("a DO loop with a step that is not a positive constant", loop);
      return;
    }

    std::vector<SlotKey> keys = assignedSlots(loop.getRegion());
    SmallVector<Value> forInits = inits;
    for (SlotKey k : keys) forInits.push_back(current(k));
    Value end = arith::AddIOp::create(b, loc, ub, arith::ConstantIndexOp::create(b, loc, 1));
    auto forOp = scf::ForOp::create(b, loc, lb, end, step, forInits);
    auto saved = slots;
    {
      OpBuilder::InsertionGuard guard(b);
      Block *forBody = forOp.getBody();
      if (!forBody->empty() && forBody->back().hasTrait<OpTrait::IsTerminator>()) forBody->back().erase();
      b.setInsertionPointToEnd(forBody);
      values[iv] = forOp.getInductionVar();
      for (unsigned i = 0; i < inits.size(); ++i) values[body.getArgument(1 + i)] = forOp.getRegionIterArg(i);
      for (auto [i, k] : llvm::enumerate(keys)) slots[k] = forOp.getRegionIterArg(inits.size() + i);
      SmallVector<Value> next;
      walkBlock(body, &next);
      if (ok()) {
        SmallVector<Value> out;
        for (auto [i, v] : llvm::enumerate(next)) out.push_back(cast(v, forInits[i].getType(), loop));
        for (auto [i, k] : llvm::enumerate(keys))
          out.push_back(cast(current(k), forInits[inits.size() + i].getType(), loop));
        scf::YieldOp::create(b, loc, out);
      }
    }
    slots = saved;
    if (!ok()) return;
    for (auto [i, r] : llvm::enumerate(loop.getResults())) values[r] = forOp.getResult(i);
    for (auto [i, k] : llvm::enumerate(keys)) slots[k] = forOp.getResult(inits.size() + i);
  }
};

bool isIntentIn(Value arg) {
  for (Operation *user : arg.getUsers())
    if (auto d = dyn_cast<fir::DeclareOp>(user))
      if (auto attrs = d.getFortranAttrs())
        return fir::bitEnumContainsAny(*attrs, fir::FortranVariableFlagsEnum::intent_in);
  return false;
}


ImportResult importFortranKernel(MLIRContext &ctx, const ImportOptions &options) {
  ImportResult result;
  auto failWith = [&](const std::string &reason) {
    result.ok = false;
    result.reason = reason;
    result.manifest = writeFailedManifest(options.kernelName, options.ndim, reason, fortranImporterId());
    return std::move(result);
  };
  if (options.ndim < 1 || options.ndim > 3) return failWith("the block dimension must be 1, 2 or 3");
  if (options.sourceFile.empty()) return failWith("no kernel file was given");

  auto absolute = [](const std::string &path) {
    llvm::SmallString<256> abs(path);
    llvm::sys::fs::make_absolute(abs);
    llvm::sys::path::remove_dots(abs, /*remove_dot_dot=*/true);
    return std::string(abs);
  };
  std::string kernelFile = absolute(options.sourceFile);
  if (!llvm::sys::fs::exists(kernelFile)) return failWith("cannot read " + kernelFile);
  result.dependencies.push_back(kernelFile);

  llvm::SmallString<128> workDir;
  if (llvm::sys::fs::createUniqueDirectory("ops-import-fortran", workDir))
    return failWith("cannot create a temporary directory");
  llvm::scope_exit removeWork([&] { llvm::sys::fs::remove_directories(workDir); });

  std::vector<std::string> common = {"-module-dir", std::string(workDir)};
  if (std::strlen(OPS_FLANG_INTRINSIC_MODULE_DIR) != 0) {
    common.push_back("-fintrinsic-modules-path");
    common.push_back(OPS_FLANG_INTRINSIC_MODULE_DIR);
  }
  for (size_t i = 0; i < options.clangArgs.size(); ++i) {
    const std::string &a = options.clangArgs[i];
    if ((a == "-I" || a == "-D" || a == "-U") && i + 1 < options.clangArgs.size()) {
      common.push_back(a);
      common.push_back(options.clangArgs[++i]);
    } else if (a.size() > 2 && (a.rfind("-I", 0) == 0 || a.rfind("-D", 0) == 0 || a.rfind("-U", 0) == 0)) {
      common.push_back(a);
    }
  }
  common.push_back("-I" + std::string(llvm::sys::path::parent_path(kernelFile)));

  llvm::InitializeNativeTarget();

  std::vector<std::string> uses;
  std::vector<std::string> moduleFIR;
  for (const std::string &m : options.modules) {
    std::string path = absolute(m);
    auto buffer = llvm::MemoryBuffer::getFile(path);
    if (!buffer) return failWith("cannot read the module source " + path);
    for (std::string &name : definedModules((*buffer)->getBuffer())) uses.push_back(std::move(name));
    result.dependencies.push_back(path);
    // Lowered, not only checked: the values of its `parameter` arrays are only in its own FIR.
    std::vector<std::string> args = common;
    args.push_back("-emit-fir");
    args.push_back(path);
    CaptureFIRAction action;
    if (!runFlang(action, args))
      return failWith("flang could not compile the module source " + path + " (see the errors above)");
    llvm::raw_string_ostream os(moduleFIR.emplace_back());
    action.printWithLocations(os);
  }

  llvm::SmallString<128> wrapperPath(workDir);
  llvm::sys::path::append(wrapperPath, kWrapperModule.str() + ".F90");
  {
    std::error_code ec;
    llvm::raw_fd_ostream os(wrapperPath, ec, llvm::sys::fs::OF_Text);
    if (ec) return failWith("cannot write " + std::string(wrapperPath));
    os << wrapperSource(options.ndim, uses, kernelFile);
  }
  std::string firText;
  {
    std::vector<std::string> args = common;
    args.push_back("-emit-fir");
    args.push_back(std::string(wrapperPath));
    CaptureFIRAction action;
    if (!runFlang(action, args)) return failWith("flang could not compile " + kernelFile + " (see the errors above)");
    llvm::raw_string_ostream os(firText);
    action.printWithLocations(os);
  }

  ctx.loadDialect<fir::FIROpsDialect, func::FuncDialect, arith::ArithDialect, math::MathDialect, scf::SCFDialect,
                  DLTIDialect, LLVM::LLVMDialect, OPSDialect>();
  OwningOpRef<ModuleOp> firModule = parseSourceString<ModuleOp>(firText, &ctx);
  if (!firModule) return failWith("cannot parse the FIR flang produced for " + kernelFile);
  std::vector<OwningOpRef<ModuleOp>> depModules;
  SmallVector<ModuleOp> firModules{*firModule};
  for (const std::string &text : moduleFIR) {
    depModules.push_back(parseSourceString<ModuleOp>(text, &ctx));
    if (!depModules.back()) return failWith("cannot parse the FIR flang produced for a module source");
    firModules.push_back(*depModules.back());
  }

  std::string wanted = llvm::StringRef(options.kernelName).lower();
  func::FuncOp firFn;
  firModule->walk([&](func::FuncOp fn) {
    auto [kind, parts] = fortranName(fn.getSymName());
    if (!fn.isDeclaration() && kind == fir::NameUniquer::NameKind::PROCEDURE && parts.name == wanted && parts.procs.empty())
      firFn = fn;
  });
  if (!firFn) return failWith("the subroutine '" + options.kernelName + "' was not found in " + kernelFile);
  if (firFn.getNumResults() != 0) return failWith("'" + options.kernelName + "' is a function; OPS kernels are subroutines");
  if (firFn.getBody().getBlocks().size() != 1)
    return failWith("the kernel has unstructured control flow (GOTO, EXIT, CYCLE, RETURN...), which is not supported");

  if (!options.kinds.empty() && options.kinds.size() != firFn.getNumArguments())
    return failWith("the kernel has " + std::to_string(firFn.getNumArguments()) + " arguments, " +
                    std::to_string(options.kinds.size()) + " kinds were given");
  Builder bld(&ctx);
  std::vector<FParam> params(firFn.getNumArguments());
  for (unsigned i = 0; i < firFn.getNumArguments(); ++i) {
    FParam &p = params[i];
    p.firArg = firFn.getArgument(i);
    if (auto name = firFn.getArgAttrOfType<StringAttr>(i, "fir.bindc_name")) p.name = name.str();
    else p.name = "#" + std::to_string(i + 1);
    auto ref = dyn_cast<fir::ReferenceType>(p.firArg.getType());
    if (!ref) return failWith("argument '" + p.name + "' is not a scalar or an explicit-shape array");
    Type elem = ref.getEleTy();
    if (auto seq = dyn_cast<fir::SequenceType>(elem)) {
      p.isArray = true;
      elem = seq.getEleTy();
    }
    if (!elem.isIntOrFloat() || elem.isInteger(1) || !isSupportedElementType(elem))
      return failWith("argument '" + p.name + "' has an element type that is not supported (" + typeText(elem) + ")");
    p.elem = elem;
    p.isConst = isIntentIn(p.firArg);
  }

  if (!options.kinds.empty()) {
    for (size_t i = 0; i < params.size(); ++i) {
      const std::string &k = options.kinds[i];
      if (k == "acc") params[i].kind = ParamSummary::Acc;
      else if (k == "gbl") params[i].kind = ParamSummary::Gbl;
      else if (k == "red" || k == "reduce") params[i].kind = ParamSummary::Red;
      else if (k == "idx") params[i].kind = ParamSummary::Idx;
      else return failWith("unknown parameter kind '" + k + "'");
    }
  } else {
    // Without the translator's kinds: subscripted with OPS_ACCn -> dat; an array named idx -> index; a scalar that is
    // assigned -> reduction; anything else -> read-only global.
    std::vector<bool> accStyle(params.size()), stored(params.size());
    firFn.walk([&](fir::ArrayCoorOp ac) {
      Ref r = describeRef(ac.getResult(), params);
      if (r.kind == Ref::Param && r.subscripts.size() == 1 && accCall(r.subscripts[0])) accStyle[r.param] = true;
    });
    firFn.walk([&](fir::StoreOp st) {
      Ref r = describeRef(st.getMemref(), params);
      if (r.kind == Ref::Param) stored[r.param] = true;
    });
    for (auto [i, p] : llvm::enumerate(params)) {
      if (accStyle[i]) p.kind = ParamSummary::Acc;
      else if (p.isArray && llvm::StringRef(p.name).equals_insensitive("idx")) p.kind = ParamSummary::Idx;
      else if (!p.isArray && stored[i]) p.kind = ParamSummary::Red;
      else p.kind = ParamSummary::Gbl;
    }
  }
  for (FParam &p : params) {
    if (p.kind == ParamSummary::Acc && !p.isArray)
      return failWith("dat argument '" + p.name + "' is a scalar (declare it as an array, e.g. dimension(1), and "
                      "subscript it with OPS_ACCn)");
    if (p.kind == ParamSummary::Idx && (!p.isArray || !p.elem.isInteger(32)))
      return failWith("index argument '" + p.name + "' must be an integer(4) array");
  }

  OwningOpRef<ModuleOp> module = ModuleOp::create(bld.getUnknownLoc());
  auto signature = [&] {
    SmallVector<Type> types;
    for (FParam &p : params) {
      switch (p.kind) {
      case ParamSummary::Acc: types.push_back(AccType::get(&ctx, p.elem, options.ndim, p.ncomp)); break;
      case ParamSummary::Gbl: types.push_back(GblType::get(&ctx, p.elem, p.gblDim)); break;
      case ParamSummary::Red: types.push_back(RedType::get(&ctx, p.elem)); break;
      case ParamSummary::Idx: break;
      }
    }
    return types;
  };
  OpBuilder mb(module->getBody(), module->getBody()->begin());
  auto kernel = KernelOp::create(mb, bld.getUnknownLoc(), options.kernelName, bld.getFunctionType(signature(), {}));
  Block *entry = kernel.addEntryBlock();
  unsigned argNo = 0;
  for (FParam &p : params)
    if (p.kind != ParamSummary::Idx) p.arg = entry->getArgument(argNo++);

  FIRKernelWalker walker(ctx, firModules, firFn, params, options.ndim);
  walker.builder().setInsertionPointToStart(entry);
  walker.run();
  for (const std::string &w : walker.warnings()) result.warnings.push_back(w);
  if (!walker.ok()) return failWith(walker.error());

  {
    SmallVector<Type> types = signature();
    for (auto [i, t] : llvm::enumerate(types)) entry->getArgument(i).setType(t);
    kernel.setFunctionType(bld.getFunctionType(types, {}));
  }
  walker.builder().setInsertionPointToEnd(entry);
  ReturnOp::create(walker.builder(), bld.getUnknownLoc(), ValueRange{});
  for (bool changed = true; changed;) {
    changed = false;
    SmallVector<Operation *> dead;
    kernel.walk<WalkOrder::PostOrder>([&](Operation *op) {
      if (op != kernel && isOpTriviallyDead(op)) dead.push_back(op);
    });
    for (Operation *op : dead) {
      if (!op->use_empty()) continue;
      op->erase();
      changed = true;
    }
  }
  if (failed(verify(*module))) return failWith("the imported kernel does not verify");

  KernelSummary summary;
  summary.kernel = options.kernelName;
  summary.ndim = options.ndim;
  for (const FParam &p : params) summary.params.push_back(p);
  summary.consts = walker.constUses();
  summary.idxAxesRead = walker.idxAxesRead();
  summary.droppedPrintf = walker.droppedPrintf();
  result.manifest = writeManifest(summary, kernel, *module, fortranImporterId());
  result.ok = true;
  result.module = std::move(module);
  return result;
}

